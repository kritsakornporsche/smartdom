const { Client } = require('ssh2');

const conn = new Client();

conn.on('ready', async () => {
  const runCmd = (cmd) => new Promise((resolve) => {
    console.log(`\n> ${cmd}`);
    conn.exec(cmd, (err, stream) => {
      if (err) {
        console.error('Exec error:', err);
        return resolve();
      }
      stream.on('close', () => resolve())
            .on('data', d => process.stdout.write(d))
            .stderr.on('data', d => process.stderr.write(d));
    });
  });

  // Extract all app names from dump.pm2
  await runCmd('powershell -Command "Select-String -Path C:\\Users\\buain\\.pm2\\dump.pm2 -Pattern \'\"name\":|\"args\":\'"');

  // Try pm2 resurrect to see if PM2 restores it properly
  await runCmd('cmd /c "pm2 resurrect"');
  await runCmd('cmd /c "pm2 list"');

  setTimeout(() => {
    conn.end();
  }, 1000);
});

conn.on('error', (err) => {
  console.error('SSH Error:', err.message);
});

